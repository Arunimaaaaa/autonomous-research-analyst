import pytest
import asyncio
from app.orchestrator.graph import research_graph
from app.orchestrator.state import AgentState


@pytest.mark.asyncio
async def test_research_graph_execution():
    """Tests the full LangGraph research workflow end-to-end."""
    initial_state: AgentState = {
        "run_id": "test-run-123",
        "ticker": "AAPL",
        "question": "What is Apple's financial health and key risks?",
        "tasks": [],
        "documents": [],
        "metrics": [],
        "artifacts": [],
        "agent_messages": [],
        "report_draft": None,
        "verification_errors": [],
        "iteration_count": 0,
        "is_verified": False,
    }

    final_state = await research_graph.ainvoke(initial_state)

    # 1. Verify tasks were generated by planner
    assert len(final_state["tasks"]) >= 4, "Planner should generate at least 4 tasks"

    # 2. Verify data agent fetched documents
    assert len(final_state["documents"]) >= 1, "Data agent should ingest at least 1 document"
    assert final_state["documents"][0]["source_type"] == "sec_filing_10k"

    # 3. Verify analyst computed metrics and artifacts
    assert len(final_state["metrics"]) >= 2, "Analyst agent should compute at least 2 metrics"
    assert len(final_state["artifacts"]) >= 1, "Analyst agent should generate at least 1 artifact"

    # 4. Verify writer generated report draft with citations and disclaimer
    report_draft = final_state.get("report_draft")
    assert report_draft is not None, "Writer agent must produce a report draft"
    assert "AAPL" in report_draft["markdown"]
    assert "DISCLAIMER" in report_draft["disclaimer"]
    assert len(report_draft["citations"]) >= 2, "Report must contain at least 2 citations"

    # 5. Verify critic validation passed
    assert final_state["is_verified"] is True, "Critic agent should verify all citations"
    assert len(final_state["verification_errors"]) == 0, "There should be no unresolvable citation errors"

    # 6. Verify chronological agent trace was recorded
    assert len(final_state["agent_messages"]) >= 5, "Trace must contain messages from all nodes"
